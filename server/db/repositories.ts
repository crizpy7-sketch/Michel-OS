/**
 * Repositories (Agent B2).
 *
 * These move rows. They do not decide anything.
 *
 * That sentence is the whole design. `authorize()` in `domains/household` is
 * the single place access is decided, and the API tier calls it before it calls
 * anything here. If a repository also checked permissions there would be two
 * rules that could disagree, and the one that disagreed silently would be the
 * one nobody read. What repositories DO enforce is **tenancy**, because that is
 * not a permission question — it is "this row is not yours to see", and it
 * belongs in the WHERE clause of every single query so that forgetting it is
 * impossible rather than merely discouraged.
 *
 * Three conventions:
 *
 *   - Every read takes `householdId` and puts it in the WHERE clause. There is
 *     no `findById(id)` anywhere in this file, on purpose: an id alone is an
 *     invitation to leak across tenants.
 *   - Every write that produces something searchable pushes a `SearchDocument`
 *     in the SAME transaction. Search deliberately cannot read domain tables
 *     (Agent K's design), so an un-pushed row is an invisible row — and doing it
 *     in the transaction is what stops a crash between the two leaving the index
 *     lying.
 *   - Ids are generated by the database (`gen_random_uuid()`), not by the
 *     caller and not here. The domain modules refuse to invent identity; so
 *     does this layer.
 */

