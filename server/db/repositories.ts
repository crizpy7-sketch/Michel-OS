export async function insertSale(tx: Queryable, householdId: UUID, sale: Omit<Sale, 'id'>): Promise<Sale | null> {
  if (!(await assertBusinessInHousehold(tx, householdId, sale.businessId))) return null;
  const { rows } = await tx.query<SaleRow>(
    `insert into sale (business_id, at, tax_collected_cents, channel) values ($1,$2,$3,$4) returning *`,
    [sale.businessId, sale.at, sale.taxCollectedCents ?? null, sale.channel ?? null],
  );
  const saleId = rows[0]!.id;
  let line = 0;
  for (const item of sale.items) {
    line += 1;
    await tx.query(
      `insert into sale_item (sale_id, line_no, product_id, quantity, unit_price_cents)
       values ($1,$2,$3,$4,$5)`,
      [saleId, line, item.productId, item.quantity, item.unitPriceCents],
    );
  }
  return getSale(tx, householdId, saleId);
}

export async function getSale(tx: Queryable, householdId: UUID, saleId: UUID): Promise<Sale | null> {
  const { rows } = await tx.query<SaleRow>(
    `select s.* from sale s join business b on b.id = s.business_id
      where s.id = $1 and b.household_id = $2`,
    [saleId, householdId],
  );
  if (rows.length === 0) return null;
  const items = await tx.query<{ product_id: string; quantity: number; unit_price_cents: number }>(
    `select product_id, quantity, unit_price_cents from sale_item where sale_id = $1 order by line_no`,
    [saleId],
  );
  return toSale({ ...rows[0]!, items: items.rows });
}

export async function listSales(
  tx: Queryable, householdId: UUID, businessId: UUID, window?: { from: string; to: string },
): Promise<Sale[]> {
  if (!(await assertBusinessInHousehold(tx, householdId, businessId))) return [];
  const { rows } = await tx.query<SaleRow>(
    `select * from sale
      where business_id = $1
        and ($2::timestamptz is null or at >= $2)
        and ($3::timestamptz is null or at < $3)
      order by at asc, id asc`,
    [businessId, window?.from ?? null, window?.to ?? null],
  );
  if (rows.length === 0) return [];

  const items = await tx.query<{ sale_id: string; product_id: string; quantity: number; unit_price_cents: number }>(
    `select sale_id, product_id, quantity, unit_price_cents from sale_item
      where sale_id = any($1::uuid[]) order by sale_id, line_no`,
    [rows.map((r) => r.id)],
  );
  const byId = new Map<string, typeof items.rows>();
  for (const item of items.rows) {
    const bucket = byId.get(item.sale_id);
    if (bucket) bucket.push(item);
    else byId.set(item.sale_id, [item]);
  }
  return rows.map((r) => toSale({ ...r, items: byId.get(r.id) ?? [] }));
}

