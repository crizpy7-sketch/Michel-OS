/** Every household a login belongs to, for the household switcher. */
export async function listHouseholdsForUser(
  tx: Queryable,
  userId: UUID,
): Promise<Array<{ household: Household; member: Member }>> {
  const { rows } = await tx.query<HouseholdRow & { m_id: string }>(
    `select h.*, m.id as m_id
       from household h join member m on m.household_id = h.id
      where m.user_id = $1 and m.active
      order by h.created_at asc`,
    [userId],
  );
  const out: Array<{ household: Household; member: Member }> = [];
  for (const row of rows) {
    const member = await getMember(tx, row.id, row.m_id);
    if (member !== null) out.push({ household: toHousehold(row), member });
  }
  return out;
}

