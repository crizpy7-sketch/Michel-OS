/**
 * Upsert one search document. Called inside the caller's transaction.
 *
 * `on conflict … do update` rather than delete-then-insert so that a re-index
 * of an unchanged row does not briefly make it unfindable.
 */
export async function indexDocument(tx: Queryable, doc: SearchDocument): Promise<void> {
  await tx.query(
    `insert into search_document (entity, id, household_id, title, body, domain, at, member_ids, business_id)
     values ($1,$2,$3,$4,$5,$6,$7,$8,$9)
     on conflict (entity, id) do update set
       household_id = excluded.household_id,
       title        = excluded.title,
       body         = excluded.body,
       domain       = excluded.domain,
       at           = excluded.at,
       member_ids   = excluded.member_ids,
       business_id  = excluded.business_id`,
    [
      doc.entity, doc.id, doc.householdId, doc.title, doc.body ?? null,
      doc.domain ?? null, doc.at ?? null, doc.memberIds ?? null, doc.businessId ?? null,
    ],
  );
}

export async function unindexDocument(tx: Queryable, entity: SearchEntity, id: string): Promise<void> {
  await tx.query(`delete from search_document where entity = $1 and id = $2`, [entity, id]);
}

/**
 * Search, scoped to a household and to the entities the caller may see.
 *
 * Ranking is Postgres `ts_rank_cd` over the weighted vector the trigger
 * maintains, with recency as the tie-break. The permission decision about WHICH
 * entities to pass in belongs to the caller — this function will happily search
 * whatever it is told to, which is precisely why the API tier computes that
 * list from `authorize()` and never from user input.
 */
export async function searchDocuments(
  tx: Queryable,
  householdId: UUID,
  query: string,
  entities: readonly SearchEntity[],
  options: { limit?: number; businessId?: UUID } = {},
): Promise<Array<SearchDocument & { rank: number }>> {
  if (entities.length === 0 || query.trim().length === 0) return [];

  const { rows } = await tx.query<SearchDocumentRow & { rank: number }>(
    `select entity, id, household_id, title, body, domain, at, member_ids, business_id,
            ts_rank_cd(tsv, plainto_tsquery('simple', $2)) as rank
       from search_document
      where household_id = $1
        and entity = any($3::text[])
        and tsv @@ plainto_tsquery('simple', $2)
        and (business_id is null or business_id = $4)
      order by rank desc, at desc nulls last, entity asc, id asc
      limit $5`,
    [householdId, query, entities as string[], options.businessId ?? null, options.limit ?? 20],
  );

  return rows.map((r) => ({ ...toSearchDocument(r), rank: Number(r.rank) }));
}

